export function translate(lang: Lang, text: string, vars?: Vars) {
  const value = lang === "ar" ? text : en[text] ?? text;
  if (!vars) return value;
  let output = value;
  for (const [key, replacement] of Object.entries(vars)) {
    output = output.replaceAll(`{${key}}`, String(replacement));
  }
  return output;
}

export function pickText(lang: Lang, ar: string, english: string) {
  return lang === "ar" ? ar : english;
}
